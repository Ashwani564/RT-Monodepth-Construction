#!/usr/bin/env python3
"""
YOLO Object Detection Evaluation - PPE Dataset
===============================================

Evaluates custom_yolo11n.pt model on PPE (Personal Protective Equipment) detection dataset.

Dataset: PPE Detection
Classes: 10 (Hardhat, Mask, NO-Hardhat, NO-Mask, NO-Safety Vest, Person, 
         Safety Cone, Safety Vest, machinery, vehicle)

Author: Ashwani
Date: November 24, 2025
"""

import os
import sys
import json
import csv
from pathlib import Path
from datetime import datetime
import torch
from ultralytics import YOLO
import numpy as np
from collections import defaultdict

# Add project root to path
PROJECT_ROOT = Path(__file__).parent.parent
sys.path.append(str(PROJECT_ROOT))


class PPEEvaluator:
    """Evaluator for YOLO model on PPE detection dataset."""
    
    # PPE dataset class mapping
    CLASS_NAMES = {
        0: 'Hardhat',
        1: 'Mask',
        2: 'NO-Hardhat',
        3: 'NO-Mask',
        4: 'NO-Safety Vest',
        5: 'Person',
        6: 'Safety Cone',
        7: 'Safety Vest',
        8: 'machinery',
        9: 'vehicle'
    }
    
    def __init__(self, model_path, data_path, output_dir):
        """
        Initialize PPE evaluator.
        
        Args:
            model_path: Path to YOLO model weights (.pt file)
            data_path: Path to PPE dataset root directory
            output_dir: Directory to save evaluation results
        """
        self.model_path = Path(model_path)
        self.data_path = Path(data_path)
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Check if model exists
        if not self.model_path.exists():
            raise FileNotFoundError(f"Model not found: {self.model_path}")
        
        # Check if dataset exists
        if not self.data_path.exists():
            raise FileNotFoundError(f"Dataset not found: {self.data_path}")
        
        # Load YOLO model
        print(f"\n{'='*70}")
        print(f"Loading YOLO model from: {self.model_path}")
        print(f"{'='*70}\n")
        self.model = YOLO(str(self.model_path))
        
        # Device info
        self.device = 'cuda' if torch.cuda.is_available() else 'mps' if torch.backends.mps.is_available() else 'cpu'
        print(f"Using device: {self.device}")
        
        # Create data.yaml for PPE dataset
        self.data_yaml = self._create_data_yaml()
        
    def _create_data_yaml(self):
        """Create data.yaml configuration for PPE dataset."""
        yaml_path = self.data_path / 'data.yaml'
        
        # Check for css-data directory structure (Roboflow format)
        css_data_dir = self.data_path / 'css-data'
        if css_data_dir.exists():
            base_dir = css_data_dir
            train_path = 'css-data/train'
            val_path = 'css-data/valid'
            test_path = 'css-data/test'
        else:
            # Check for standard images/labels structure
            images_dir = self.data_path / 'images'
            
            # Determine split structure
            if (images_dir / 'val').exists():
                train_path = 'images/train'
                val_path = 'images/val'
            elif (images_dir / 'test').exists():
                train_path = 'images/train'
                val_path = 'images/test'
            else:
                train_path = 'images'
                val_path = 'images'
        
        yaml_content = f"""# PPE Detection Dataset Configuration
# Auto-generated by evaluate_yolo_ppe.py

path: {self.data_path}
train: {train_path}
val: {val_path}

# Number of classes
nc: 10

# Class names
names:
  0: Hardhat
  1: Mask
  2: NO-Hardhat
  3: NO-Mask
  4: NO-Safety Vest
  5: Person
  6: Safety Cone
  7: Safety Vest
  8: machinery
  9: vehicle
"""
        
        with open(yaml_path, 'w') as f:
            f.write(yaml_content)
        
        print(f"Created data.yaml at: {yaml_path}\n")
        return yaml_path
    
    def evaluate(self, conf_thres=0.25, iou_thres=0.45, img_size=640):
        """
        Run evaluation on PPE dataset.
        
        Args:
            conf_thres: Confidence threshold for detections
            iou_thres: IoU threshold for NMS
            img_size: Input image size
            
        Returns:
            dict: Evaluation results
        """
        print(f"\n{'='*70}")
        print(f"Starting PPE Dataset Evaluation")
        print(f"{'='*70}")
        print(f"Confidence Threshold: {conf_thres}")
        print(f"IoU Threshold: {iou_thres}")
        print(f"Image Size: {img_size}")
        print(f"{'='*70}\n")
        
        # Run validation using ultralytics
        results = self.model.val(
            data=str(self.data_yaml),
            imgsz=img_size,
            conf=conf_thres,
            iou=iou_thres,
            device=self.device,
            verbose=True,
            save_json=True,
            plots=True,
            project=str(self.output_dir),
            name='ppe_evaluation'
        )
        
        # Extract metrics
        metrics = self._extract_metrics(results)
        
        # Save results
        self._save_results(metrics, conf_thres, iou_thres, img_size)
        
        return metrics
    
    def _extract_metrics(self, results):
        """Extract metrics from validation results."""
        metrics = {
            'timestamp': datetime.now().strftime('%Y%m%d_%H%M%S'),
            'model': str(self.model_path.name),
            'dataset': 'PPE Detection',
            'num_classes': 10,
            'class_names': self.CLASS_NAMES,
        }
        
        # Overall metrics
        if hasattr(results, 'box'):
            box_metrics = results.box
            metrics['overall'] = {
                'mAP50': float(box_metrics.map50) if hasattr(box_metrics, 'map50') else 0.0,
                'mAP50-95': float(box_metrics.map) if hasattr(box_metrics, 'map') else 0.0,
                'precision': float(box_metrics.mp) if hasattr(box_metrics, 'mp') else 0.0,
                'recall': float(box_metrics.mr) if hasattr(box_metrics, 'mr') else 0.0,
            }
            
            # Per-class metrics
            if hasattr(box_metrics, 'maps') and box_metrics.maps is not None:
                metrics['per_class'] = {}
                for idx, class_name in self.CLASS_NAMES.items():
                    if idx < len(box_metrics.maps):
                        metrics['per_class'][class_name] = {
                            'class_id': idx,
                            'mAP50-95': float(box_metrics.maps[idx]) if box_metrics.maps[idx] is not None else 0.0,
                            'precision': float(box_metrics.p[idx]) if hasattr(box_metrics, 'p') and idx < len(box_metrics.p) else 0.0,
                            'recall': float(box_metrics.r[idx]) if hasattr(box_metrics, 'r') and idx < len(box_metrics.r) else 0.0,
                        }
        else:
            # Fallback if results structure is different
            metrics['overall'] = {
                'mAP50': 0.0,
                'mAP50-95': 0.0,
                'precision': 0.0,
                'recall': 0.0,
            }
            metrics['per_class'] = {}
        
        # Speed metrics
        if hasattr(results, 'speed'):
            metrics['speed'] = {
                'preprocess_ms': results.speed['preprocess'],
                'inference_ms': results.speed['inference'],
                'postprocess_ms': results.speed['postprocess'],
                'total_ms': sum(results.speed.values()),
            }
        
        return metrics
    
    def _save_results(self, metrics, conf_thres, iou_thres, img_size):
        """Save evaluation results to files."""
        timestamp = metrics['timestamp']
        
        # Save JSON
        json_path = self.output_dir / f'ppe_results_{timestamp}.json'
        with open(json_path, 'w') as f:
            json.dump(metrics, f, indent=2)
        print(f"\nResults saved to: {json_path}")
        
        # Save CSV (overall metrics)
        csv_path = self.output_dir / f'ppe_results_{timestamp}.csv'
        with open(csv_path, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['Metric', 'Value'])
            writer.writerow(['Model', metrics['model']])
            writer.writerow(['Dataset', metrics['dataset']])
            writer.writerow(['Timestamp', timestamp])
            writer.writerow(['Confidence Threshold', conf_thres])
            writer.writerow(['IoU Threshold', iou_thres])
            writer.writerow(['Image Size', img_size])
            writer.writerow([])
            writer.writerow(['Overall Metrics', ''])
            for key, value in metrics['overall'].items():
                writer.writerow([key, f"{value:.4f}"])
            
            if 'speed' in metrics:
                writer.writerow([])
                writer.writerow(['Speed Metrics', ''])
                for key, value in metrics['speed'].items():
                    writer.writerow([key, f"{value:.2f} ms"])
        
        print(f"Results saved to: {csv_path}")
        
        # Save per-class CSV
        if 'per_class' in metrics and metrics['per_class']:
            per_class_csv = self.output_dir / f'ppe_per_class_{timestamp}.csv'
            with open(per_class_csv, 'w', newline='') as f:
                writer = csv.writer(f)
                writer.writerow(['Class ID', 'Class Name', 'mAP50-95', 'Precision', 'Recall'])
                for class_name, class_metrics in metrics['per_class'].items():
                    writer.writerow([
                        class_metrics['class_id'],
                        class_name,
                        f"{class_metrics['mAP50-95']:.4f}",
                        f"{class_metrics['precision']:.4f}",
                        f"{class_metrics['recall']:.4f}"
                    ])
            print(f"Per-class results saved to: {per_class_csv}")
        
        # Print summary
        self._print_summary(metrics)
    
    def _print_summary(self, metrics):
        """Print evaluation summary."""
        print(f"\n{'='*70}")
        print(f"PPE DETECTION EVALUATION SUMMARY")
        print(f"{'='*70}")
        print(f"Model: {metrics['model']}")
        print(f"Dataset: {metrics['dataset']}")
        print(f"Number of Classes: {metrics['num_classes']}")
        print(f"\nOverall Metrics:")
        print(f"  mAP@50:      {metrics['overall']['mAP50']:.4f} ({metrics['overall']['mAP50']*100:.2f}%)")
        print(f"  mAP@50-95:   {metrics['overall']['mAP50-95']:.4f} ({metrics['overall']['mAP50-95']*100:.2f}%)")
        print(f"  Precision:   {metrics['overall']['precision']:.4f} ({metrics['overall']['precision']*100:.2f}%)")
        print(f"  Recall:      {metrics['overall']['recall']:.4f} ({metrics['overall']['recall']*100:.2f}%)")
        
        if 'speed' in metrics:
            print(f"\nSpeed Metrics:")
            print(f"  Preprocess:  {metrics['speed']['preprocess_ms']:.2f} ms")
            print(f"  Inference:   {metrics['speed']['inference_ms']:.2f} ms")
            print(f"  Postprocess: {metrics['speed']['postprocess_ms']:.2f} ms")
            print(f"  Total:       {metrics['speed']['total_ms']:.2f} ms")
            print(f"  FPS:         {1000.0/metrics['speed']['total_ms']:.2f}")
        
        if 'per_class' in metrics and metrics['per_class']:
            print(f"\nTop 5 Classes by mAP@50-95:")
            sorted_classes = sorted(
                metrics['per_class'].items(),
                key=lambda x: x[1]['mAP50-95'],
                reverse=True
            )[:5]
            for class_name, class_metrics in sorted_classes:
                print(f"  {class_name:20s}: {class_metrics['mAP50-95']:.4f} "
                      f"(P: {class_metrics['precision']:.3f}, R: {class_metrics['recall']:.3f})")
        
        print(f"{'='*70}\n")


def main():
    """Main evaluation function."""
    # Paths
    model_path = PROJECT_ROOT / 'custom_yolo11n.pt'
    data_path = PROJECT_ROOT / 'datasets' / 'yolo' / 'ppe-detection'
    output_dir = PROJECT_ROOT / 'stage2_benchmark' / 'results' / 'ppe'
    
    # Create evaluator
    evaluator = PPEEvaluator(
        model_path=model_path,
        data_path=data_path,
        output_dir=output_dir
    )
    
    # Run evaluation
    metrics = evaluator.evaluate(
        conf_thres=0.25,  # Standard confidence threshold
        iou_thres=0.45,   # Standard IoU threshold for NMS
        img_size=640      # Standard YOLO input size
    )
    
    print("\n✓ PPE evaluation completed successfully!")
    print(f"Results saved in: {output_dir}")


if __name__ == '__main__':
    main()
